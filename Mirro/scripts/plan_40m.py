# -*- coding: utf-8 -*-
"""
Расчёт плана 30-40 млн примеров в 50-80 ГБ.
"""
print("=" * 64)
print("  ПЛАН: 30-40 МЛН ПРИМЕРОВ В 50-80 ГБ")
print("=" * 64)

rows = [
    # (источник, млн примеров, ГБ, оценка из проверки)
    ("Wikipedia RU (полный раздел)", 8.0, 4.9, "21 файл parquet, ~5млн статей с текстом"),
    ("LMSYS Chat 1M (диалоги)", 1.0, 1.5, "6 файлов, 1 млн человеческих диалогов"),
    ("Уже есть (RU+Math+Code+Design)", 0.9, 1.3, "910k в индексе"),
    ("RefinedWeb sample (веб-корпус)", 12.0, 25.0, "выборка clean-веба, большие тексты"),
    ("Tatoeba/CC-Matrix (параллельные)", 3.0, 6.0, "предложения RU-EN"),
    ("StackOverflow posts (10M+)", 8.0, 12.0, "вопрос-ответ программирование"),
    ("История чатов + генерация (синтетика)", 5.0, 4.0, "сгенерированные QA-пары"),
]

total_ex = sum(r[1] for r in rows)
total_gb = sum(r[2] for r in rows)

print(f"\n{'Источник':<44} {'млн':>5} {'ГБ':>5}")
print("-" * 64)
for name, ex, gb, note in rows:
    print(f"{name:<44} {ex:5.1f} {gb:5.1f}  {note}")
print("-" * 64)
print(f"{'ИТОГО':<44} {total_ex:5.1f} {total_gb:5.1f}")

print(f"\nДиск D: 251 ГБ свободно — запас {(251 - total_gb):.0f} ГБ")
print(f"Индекс для быстрых ответов: ~1-2 млн топ самых ценных")
print(f"Остальные ~30+ млн: сегменты parquet на диске (RAG-подбор)")

# Оценка времени скачивания
print(f"\nОценка времени (при 5 МБ/с): {total_gb*1024/5/3600:.0f} ч")

# Проверка: реально ли 40 млн
print(f"\nПри среднем примере 1.5 КБ: 40 млн ≈ {40*1.5/1024:.0f} ГБ jsonl")
print(f"В 50-80 ГБ: можно хранить 40 млн примеров с запасом")
print("=" * 64)