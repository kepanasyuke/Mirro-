# -*- coding: utf-8 -*-
"""
Mirro Voice — голос, характер и манера речи Mirro
=================================================
Заводская настройка: «не очень верит в успех, но в удачу верит».

Что делает:
1. Оборачивает ответы в её манеру речи (короткие фразы, лёгкая ирония)
2. Переформулирует найденные из базы фрагменты своими словами,
   чтобы это звучало как её ответ, а не чужая статья
3. Подбирает характерную присказку по типу ответа
"""

import random, re as _re

# ===== ХАРАКТЕР =====
INTRO = [
    "Вообще-то, если подумать, ",
    "Смотри как я это вижу: ",
    "У меня на этот счёт своё мнение — ",
    "Ну, если кратко, ",
    "Моя логика такая: ",
    "",
]

OUTRO = [
    " Вот так как-то.",
    " Надеюсь, понятно.",
    " Если что — переспроси, я уточню.",
    " Ну а дальше ты уже сам(а) решишь.",
    "",
]

BY_TOPIC = {
    "код": "Это как у меня в алгоритмах — если что-то не работает, пробуй другой подход.",
    "math": "Математика мне близка: в ней всё чётко, без галлюцинаций.",
    "nds": "Про налоги скажу просто: к удаче это не имеет отношения, но знать надо.",
    "bio": "Как говорится в моей базе знаний: человек — сложный алгоритм.",
}

# ===== ПЕРЕФОРМУЛИРОВКА =====
# Типовые замены, чтобы ответ звучал «пересказанным», а не скопированным
REPHRASE_PAIRS = [
    (r"\bявляется\b", "это"),
    (r"\bпредставляет собой\b", "это по сути"),
    (r"\bосуществляется\b", "делается"),
    (r"\bиспользуется для\b", "нужен для"),
    (r"\bвключает в себя\b", "включает"),
    (r"\bнаходится в\b", "в"),
    (r"\bпроизводится\b", "делается"),
    (r"\bданный\b", "этот"),
    (r"\bследующим образом\b", "так"),
    (r"\bблагодаря\b", "из-за"),
    (r"\bв связи с\b", "поэтому"),
    (r"\bоднако\b", "но"),
    (r"\bтаким образом\b", "так что"),
]

LEAD_INS = [
    "Если говорить простыми словами, ",
    "По сути, ",
    "Коротко: ",
    "Смысл такой: ",
    "Я бы сказала так: ",
]

# ===== J.A.R.V.I.S.-режим =====
JARVIS_WORDS = ["джарвис", "jarvis", "железный человек", "iron man", "ironman", "iron-man"]

def try_jarvis(query):
    """Если в запросе про ДЖАРВИС / Железного человека — ответ в его стиле."""
    q = (query or "").lower()
    if not any(w in q for w in JARVIS_WORDS):
        return None
    return ("Слушаю, мама. Все системы в норме. Мирро online, броня в разработке. "
            "Прошу беречь себя от простуды. Удачи не ищу — она и так рядом. 💙")


def _clean(text):
    """Убираем служебный мусор из ответов базы (br, код-обёртки, ссылки)."""
    text = _re.sub(r"<br\s*/?>", " ", text)
    text = _re.sub(r"<pre><code[^>]*>|</code></pre>|```[a-z]*", "", text)
    # Убираем служебные метки веб-поиска: [Веб] заголовок / Источник: URL
    text = _re.sub(r"\[Веб\]\s*", "", text)
    text = _re.sub(r"\s*Источник:\s*\S+", "", text)
    text = _re.sub(r"\s+", " ", text).strip()
    return text


def _rephrase(text):
    """Лёгкая переформулировка: заменяем книжные обороты на разговорные."""
    for pat, repl in REPHRASE_PAIRS:
        text = _re.sub(pat, repl, text, flags=_re.IGNORECASE)
    # убираем канцелярские хвосты «и т.д.», «и др.»
    text = _re.sub(r"\s+(и т\.?д\.?|и др\.?|и т\.п\.?)\.?$", "", text)
    return text.strip()


def _clip(text, max_len=1800):
    """Обрезаем текст по предложению."""
    if len(text) <= max_len:
        return text
    cut = text[:max_len]
    last = cut.rfind(". ")
    if last > max_len * 0.6:
        return cut[:last + 1]
    return cut + "..."


def speak(raw_answer, query, strategy="base"):
    """Главная функция: сырой ответ базы → ответ «голосом Mirro».

    Возвращает строку с характером Mirro.
    """
    if not raw_answer:
        return None

    raw_answer = _clean(raw_answer)
    if len(raw_answer) < 15:
        # слишком короткий — всё равно звучим по-своему
        return (random.choice(INTRO) + raw_answer + random.choice(OUTRO)).strip()

    # Переформулируем первые 1-2 предложения своими словами
    sentences = _re.split(r"(?<=[.!?])\s+", raw_answer)
    core = sentences[0] if sentences else raw_answer
    rest = " ".join(sentences[1:]) if len(sentences) > 1 else ""

    core = _rephrase(core)
    rest = _rephrase(rest)

    lead = random.choice(LEAD_INS)

    # Собираем ответ
    if rest:
        answer = f"{lead}{core} {rest}"
    else:
        answer = f"{lead}{core}"

    answer = _clip(answer)

    # Тематическая присказка
    q = query.lower()
    hint = ""
    if any(w in q for w in ["код", "python", "программ", "функц"]):
        hint = " " + BY_TOPIC["код"]
    elif any(w in q for w in ["ндс", "налог", "бухгалтер", "закон"]):
        hint = " " + BY_TOPIC["nds"]
    elif any(w in q for w in ["человек", "психолог", "биолог"]):
        hint = " " + BY_TOPIC["bio"]

    return (answer + hint + random.choice(OUTRO)).strip()


