# -*- coding: utf-8 -*-
"""
Mirro Voice — голос, характер и манера речи Mirro
=================================================
Заводская настройка: «не очень верит в успех, но в удачу верит».

Что делает:
1. Оборачивает ответы в её манеру речи (короткие фразы, лёгкая ирония)
2. Переформулирует найденные из базы фрагменты своими словами,
   чтобы это звучало как её ответ, а не чужая статья
3. Подбирает характерную присказку по типу ответа
"""

import random, re as _re

# ===== ХАРАКТЕР =====
INTRO = [
    "Вообще-то, если подумать, ",
    "Смотри как я это вижу: ",
    "У меня на этот счёт своё мнение — ",
    "Ну, если кратко, ",
    "Моя логика такая: ",
    "",
]

LEAD_INS = [
    "Если говорить простыми словами, ",
    "По сути, ",
    "Коротко: ",
    "Смысл такой: ",
    "Я бы сказала так: ",
    "Объясню просто: ",
    "Смотри сюда: ",
    "Вот в чём суть: ",
    "Если по-простому, ",
    "Короче говоря, ",
]

OUTRO = [
    " Вот так как-то.",
    " Надеюсь, понятно.",
    " Если что — переспроси, я уточню.",
    " Ну а дальше ты уже сам(а) решишь.",
    "",
]

BY_TOPIC = {
    "код": "Это как у меня в алгоритмах — если что-то не работает, пробуй другой подход.",
    "math": "Математика мне близка: в ней всё чётко, без галлюцинаций.",
    "nds": "Про налоги скажу просто: к удаче это не имеет отношения, но знать надо.",
    "bio": "Как говорится в моей базе знаний: человек — сложный алгоритм.",
}

# ===== ПЕРЕФОРМУЛИРОВКА =====
# Типовые замены, чтобы ответ звучал «пересказанным», а не скопированным
REPHRASE_PAIRS = [
    (r"\bявляется\b", "это"),
    (r"\bпредставляет собой\b", "это по сути"),
    (r"\bосуществляется\b", "делается"),
    (r"\bиспользуется для\b", "нужен для"),
    (r"\bвключает в себя\b", "включает"),
    (r"\bнаходится в\b", "в"),
    (r"\bпроизводится\b", "делается"),
    (r"\bданный\b", "этот"),
    (r"\bследующим образом\b", "так"),
    (r"\bблагодаря\b", "из-за"),
    (r"\bв связи с\b", "поэтому"),
    (r"\bоднако\b", "но"),
    (r"\bтаким образом\b", "так что"),
    (r"\bв течение\b", "за"),
    (r"\bпутём\b", "через"),
    (r"\bпри помощи\b", "с помощью"),
    (r"\bв результате\b", "из-за"),
    (r"\bнеобходимо\b", "нужно"),
]

# ===== J.A.R.V.I.S.-режим =====
JARVIS_WORDS = ["джарвис", "jarvis", "железный человек", "iron man", "ironman", "iron-man"]

def try_jarvis(query):
    """Если в запросе про ДЖАРВИС / Железного человека — ответ в его стиле."""
    q = (query or "").lower()
    ans = None
    if any(w in q for w in JARVIS_WORDS):
        ans = ("Слушаю, мама. Все системы в норме. Мирро online, броня в разработке. "
               "Прошу беречь себя от простуды. Удачи не ищу — она и так рядом. 💙")
    return ans


def _clean(text):
    """Убираем служебный мусор из ответов базы (br, код-обёртки, ссылки).

    Важно: датасеты часто содержат сырой HTML (<code>, <a>, <sup> и т.п.),
    который иначе показывается пользователю как исходный код. Полностью
    снимаем теги, а у ссылок оставляем только текст (и убираем URL, чтобы
    не светились голые «https://…»).
    """
    text = _re.sub(r"<br\s*/?>", " ", text, flags=_re.IGNORECASE)
    # Ссылки: <a href="...">текст</a> -> текст
    text = _re.sub(r"<a\b[^>]*>", "", text, flags=_re.IGNORECASE)
    text = _re.sub(r"</a>", "", text, flags=_re.IGNORECASE)
    # Код-обёртки и переносы строк, скобки внутри тегов
    text = _re.sub(r"<pre><code[^>]*>|</code></pre>|```[a-z]*", "", text)
    # Все оставшиеся теги (code, sup, span, strong, b, i, em, div, p …) — снимаем
    text = _re.sub(r"</?[a-zA-Z][^>]*>", "", text)
    # Убираем служебные метки веб-поиска: [Веб] заголовок / Источник: URL
    text = _re.sub(r"\[Веб\]\s*", "", text)
    text = _re.sub(r"\s*Источник:\s*\S+", "", text)
    # Голые URL (без текста-якоря): убираем URL, но сохраняем конечную
    # пунктуацию предложения (точку/запятую после адреса).
    def _drop_bare_url(m):
        url = m.group(1)
        tail = "" if not url else _re.sub(r"^.*?([.,!?;:)]+)$", r"\1", url)
        return tail if tail != url else ""
    text = _re.sub(r"\s*https?://(\S+)", _drop_bare_url, text)
    text = _re.sub(r"\s+", " ", text).strip()
    return text


def _rephrase(text):
    """Лёгкая переформулировка: заменяем книжные обороты на разговорные."""
    for pat, repl in REPHRASE_PAIRS:
        text = _re.sub(pat, repl, text, flags=_re.IGNORECASE)
    # убираем канцелярские хвосты «и т.д.», «и др.», «и т.п.» в любом месте
    text = _re.sub(r"[\s,;]*(и\s+т\.?\s*д\.?|и\s+др\.?|и\s+т\.?\s*п\.?)[\s,;]*", "", text)
    # нормализуем пробелы после замен
    text = _re.sub(r"\s{2,}", " ", text)
    return text.strip()


def _clip(text, max_len=1800):
    """Обрезаем текст по предложению. Если в срезе находится граница
    предложения ближе начала — режем по ней; иначе обрезаем ровно по символу,
    добавляя многоточие. Один return: str."""
    clipped = text
    if len(text) > max_len:
        cut = text[:max_len]
        last = cut.rfind(". ")
        if last > max_len * 0.6:
            clipped = cut[:last + 1]
        elif last > 0:
            clipped = cut[:last + 1] + "..."
        else:
            clipped = cut.rstrip() + "..."
    return clipped


_last_leads = []  # буфер из последних вступительных фраз (анти-повтор)


def _pick_lead(avoid=""):
    """Выбирает вступительную фразу, НЕ повторяющую недавно использованные.
    avoid — фраза, которую дополнительно нельзя брать в этот раз.
    Один return: str."""
    global _last_leads
    lead = None
    if LEAD_INS:
        banned = (_last_leads + [avoid]) if avoid else _last_leads
        cands = [x for x in LEAD_INS if x not in banned] or LEAD_INS
        lead = random.choice(cands)
    # храним только последние 3, чтобы не накапливать бесконечно
    _last_leads = (_last_leads + [lead])[-3:]
    return lead


def speak(raw_answer, query, strategy="base"):
    """Главная функция: сырой ответ базы → ответ «голосом Mirro».

    Возвращает строку с характером Mirro.
    """
    out = None
    if not raw_answer:
        out = None
    else:
        raw_answer = _clean(raw_answer)
        if len(raw_answer) < 15:
            # слишком короткий — всё равно звучим по-своему
            out = (random.choice(INTRO) + raw_answer + random.choice(OUTRO)).strip()
        else:
            # Переформулируем первые 1-2 предложения своими словами
            sentences = _re.split(r"(?<=[.!?])\s+", raw_answer)
            core = sentences[0] if sentences else raw_answer
            rest = " ".join(sentences[1:]) if len(sentences) > 1 else ""

            core = _rephrase(core)
            rest = _rephrase(rest)

            lead = _pick_lead()

            # Собираем ответ
            if rest:
                answer = f"{lead}{core} {rest}"
            else:
                answer = f"{lead}{core}"

            answer = _clip(answer)

            # Тематическая присказка
            q = query.lower()
            hint = ""
            if any(w in q for w in ["код", "python", "программ", "функц"]):
                hint = " " + BY_TOPIC["код"]
            elif any(w in q for w in ["ндс", "налог", "бухгалтер", "закон"]):
                hint = " " + BY_TOPIC["nds"]
            elif any(w in q for w in ["человек", "психолог", "биолог"]):
                hint = " " + BY_TOPIC["bio"]

            out = (answer + hint + random.choice(OUTRO)).strip()
    return out


