_LESS2 = " · ".join  # noqa

_STOP = set(("что", "такое", "почему", "как", "это", "про", "и", "в", "на"))


def _norm_question(q):
    """Нормализует вопрос для дедупа. Один return: str."""
    return re.sub(r"[^а-яёa-z0-9]+", " ", (q or "").lower()).strip()


def _existing_keys():
    """Читает все вопросы уже в facts.jsonl (дедуп). Один return: set."""
    keys = set()
    try:
        if TARGET.exists():
            for line in TARGET.read_text("utf-8").splitlines():
                try:
                    r = json.loads(line)
                    keys.add(_norm_question(r.get("instruction", "")))
                except Exception:
                    continue
    except Exception:
        keys = set()
    return keys


def run(limit=None):
    """Добавляет факты в self_learned/facts.jsonl с дедупом.
    Один return: int (добавлено)."""
    added = 0
    existing = _existing_keys()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    for q, a in FACTS:
        if limit is not None and added >= limit:
            break
        key = _norm_question(q)
        if not key or key in existing:
            continue
        rec = {"instruction": q, "input": "", "output": a, "source": "facts"}
        with open(TARGET, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
        existing.add(key)
        added += 1
    return added


def main():
    ap = argparse.ArgumentParser(description="Расширение корпуса научно-популярными фактами")
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    n = run(args.limit)
    print(f"Добавлено фактов: {n} (всего в словаре: {len(FACTS)})")


if __name__ == "__main__":
    main()