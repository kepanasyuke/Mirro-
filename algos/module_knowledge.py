def _stem_ru(word):
    """Грубый русский стеммер для сравнения словоформ (с исключениями-основами).
    Не-строка → «». Один return: str."""
    if not isinstance(word, str):
        return ""
    cached = _STEM_CACHE.get(word)
    if cached is not None:
        return cached
    stem = _stem_ru_uncached(word)
    if len(_STEM_CACHE) < 50000:
        _STEM_CACHE[word] = stem
    return stem


def _stem_ru_uncached(word):
    """Собственно стемминг без кеша. Один return: str."""
    w = word.lower()
    stem = _STEM_EXC.get(w)
    if stem is None:
        stem = w
        for suf in _RU_SUFFIXES:
            if len(w) > len(suf) + 3 and w.endswith(suf):
                cand = w[:-len(suf)]
                if len(cand) >= 2:
                    stem = cand
                break
    return stem


# Частотные стоп-слова вопроса. Они есть почти в любом описании («соседние … так,
# что …»), поэтому их совпадение с темой/описанием не несёт смысла: «что такое
# смех» не должно превращаться в пузырьковую сортировку только потому, что у той
# в «what» написано «…так, что…». Из скоринга они исключаются.
_RU_QUESTION_STOP = {
    "что", "такое", "как", "это", "где", "кто", "зачем", "почему", "сколько",
    "какой", "какая", "какие", "каких", "каким", "чем", "чему", "про", "обо",
    "об", "о", "на", "в", "с", "по", "и", "а", "не",
    "для", "если", "то", "или", "дай", "дайте", "нужно", "надо", "можно",
    "мне", "меня", "тебе", "вас", "вы", "ты",
}


def _match_by_topic(q):
    """Ищет функцию, тема которой совпадает со словами запроса, с учётом
    словоформ (стем). Главный приоритет — ЧИСЛО слов запроса, которые функция
    покрывает, затем качество совпадения. Пустой запрос → None.
    Стоп-слова вопроса игнорируются. Один return: str/None.

    Важно: матчим ТОЛЬКО по теме и имени, не по «what»-объяснению. Общие
    глаголы внутри объяснения («работает как насос») иначе перетягивали бы
    чужое понятие: на «как работает телефон» отвечало «_сердце», потому что
    «работает» есть в тексте карточки сердца."""
    if not (q or "").strip():
        return None
    words = [_stem_ru(w) for w in _norm_q(q).split()
             if len(w) > 2 and w not in _RU_QUESTION_STOP]
    scored = []
    for name, info in (fk._by_name or {}).items():
        if not isinstance(info, dict):
            continue
        topic_tokens = {_stem_ru(t) for t in _norm_q(info.get("topic", "")).split()}
        name_norm = _norm_q(name)
        hit_words = 0
        quality = 0.0
        for w in words:
            if w in topic_tokens:
                hit_words += 1
                quality += 1.0
            elif w in name_norm:
                quality += 0.4
            elif w in _norm_q(info.get("topic", "")):
                quality += 0.2
        if hit_words or quality >= 0.4:
            # полное совпадение по теме — сильный признак
            exact_topic = bool(words and set(words) <= topic_tokens)
            scored.append((hit_words, quality, exact_topic, name))
    best_name = None
    if scored:
        # сперва точное попадание по теме, затем покрытие и качество;
        # при равенстве — лексикографически первое имя (детерминизм)
        scored.sort(key=lambda x: (-x[2], -x[0], -x[1], x[3]))
        best_name = scored[0][3]
    return best_name


