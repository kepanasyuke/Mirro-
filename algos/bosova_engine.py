# Выполнимый интерпретатор простых правил Босовой.
# Правило: {"оп":"if","cond": bool_fn, "then": action, "else": action} и т.п.
# На практике для Mirro нас интересуют не абстрактные интерпретаторы, а
# готовые маленькие решатели, работающие по босовским конструкциям. Ниже —
# несколько таких: они доказывают «выполнимость», а не просто показывают схему.


def _числа(query):
    return [int(x) for x in _re.findall(r"\d+", query)]


def решить_арифметику(query):
    """ЦИКЛ ПОКА + ветвление Босовой над числами из вопроса.

    Пока в вопросе есть операция (плюс/минус/умножить/процент),
    прогнать по правилу ЕСЛИ/ТО/ИНАЧЕ и вернуть результат. Возвращает
    (ответ, схема) или (None, схема), если вычисление не распознано.
    """
    q = query.lower()
    nums = _числа(query)
    # процент: "X% от Y"
    m = _re.search(r"(\d+)\s*%\s*(?:от|из|о т)?\s*(\d+)", q.lower())
    if m and "процент" in q or (m and "% от" in q):
        p, v = int(m.group(1)), int(m.group(2))
        ans = v * p // 100
        scheme = ("ЦИКЛ ПОКА <в вопросе есть проценты>",
                  [f"ВВОД: {p}% от {v}",
                   f"ВЫЧИСЛИТЬ: {v} × {p} / 100",
                   f"ВЫВОД: {ans}"])
        return ans, scheme

    multiplier = None
    if ("умнож" in q or "×" in q or "*" in q or "найди произведение" in q) and len(nums) >= 2:
        multiplier = nums[-2] * nums[-1]
    elif "плюс" in q or "сумм" in q or "+" in q or "сколько будет" in q:
        if len(nums) >= 2:
            # сложение
            a, b = nums[-2], nums[-1]
            # если это "a - b", минус стоит перед
            mn = _re.search(r"(\d+)\s*-\s*(\d+)", q)
            multiplier = (a - b) if mn and str(a) + "-" + str(b) in q.replace(" ", "") else (a + b)
    elif "минус" in q or "-" in q:
        m2 = _re.search(r"(\d+)\s*-\s*(\d+)", q)
        if m2 and len(nums) >= 2:
            multiplier = int(m2.group(1)) - int(m2.group(2))

    if multiplier is None:
        return None, ("Следование (нет операции)",
                      ["НАЧАЛО", "ОПРЕДЕЛИТЬ: чисел нет или операция не распознана", "КОНЕЦ → без результата"])
    scheme = ("Ветвление ЕСЛИ/ТО + вычисление",
              [f"ВВОД: числа {nums}",
               f"ЕСЛИ операция распознана ТО ВЫЧИСЛИТЬ",
               f"ВЫВОД: {multiplier}"])
    return multiplier, scheme


def таблица_решений(query, факты):
    """Таблица решений Босовой: условия по строкам → вывод решения.

    факты: список (условие_true, вариант) — проверяемое на вопрос.
    Возвращает (решение, схема_таблицы).
    """
    rows = []
    решение = "НЕ ОПРЕДЕЛЕНО"
    for cond, variant in факты:
        ok = any(w in _words(query) for w in _words(cond))
        rows.append((cond, "ДА" if ok else "НЕТ"))
        if ok:
            решение = variant
    схема = ("Таблица решений ×3",
             [f"| УСЛОВИЕ: {c:<20} | {v} |" for c, v in rows],
             f"РЕШЕНИЕ → {решение}")
    return решение, схема


