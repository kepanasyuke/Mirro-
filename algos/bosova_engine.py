def run_self_check():
    """Быстрый прогон для build --check. Возвращает (ok, lines)."""
    lines = []
    checks = []
    # Арифметика
    a, _ = решить_арифметику("Сколько будет 4 + 5?")
    checks.append(("арифметика 4+5=9", a == 9))
    p, _ = решить_арифметику("Сколько будет 25% от 200?")
    checks.append(("проценты 25% от 200=50", p == 50))
    # Тройственность
    tr = тройственность("страх связан с опасностью и влияет на контроль между людьми")
    checks.append(("троичность нашла A,B,C", tr is not None and len(tr["elements"]) == 3))
    # Схемы
    s = схема_мышления("рекурсия")
    checks.append(("схема рекурсии", "Рекурсия" in s["name"]))
    for name, ok in checks:
        lines.append(f"  [{'OK' if ok else 'FAIL'}] {name}")
    return all(ok for _, ok in checks), lines


if __name__ == "__main__":
    ok, lines = run_self_check()
    print("BOSOVA ENGINE SELF-CHECK:")
    print("\n".join(lines))
    print("[summary]", "OK" if ok else "FAIL")