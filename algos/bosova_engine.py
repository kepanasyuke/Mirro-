# -*- coding: utf-8 -*-
"""
Mirro Bosova Engine — выполнимые алгоритмы по правилам Босовой
=================================================================
Три слоя, связанных в одном модуле:

1. БЛОК-СХЕМЫ БОСОВОЙ (исполняемые).
   Не просто текст-объяснение (как в algos/reasoning.py), а реальные
   конструкции, которые ВЫПОЛНЯЮТСЯ над величинами вопроса: ЕСЛИ/ТО/ИНАЧЕ,
   ЦИКЛ ПОКА, величины, таблицы решений.

2. СХЕМЫ ДЛЯ САМООПИСАНИЯ.
   Вспомогательные алгоритмы, цикл с параметром, подпрограммы, рекурсия —
   схемы, которые Mirro показывает, когда её спрашивают о её же мышлении.

3. ТРОЙСТВЕННОЕ РАССУЖДЕНИЕ «НЕЙРОН-НИГДЕ».
   По мотивам задачи трёх тел + условной информации Шеннона: если в вопросе
   есть три элемента (A, B, C), состояние каждого задаётся не «координатой»,
   а отношениями к двум другим; третья сторона C меняет пару A↔B.
   Оформлено как босовская таблица решений × 3, с исполняемым подсчётом мер.

Модуль не импортирует тяжёлый индекс — чистый, легко тестируется.
"""
import re as _re


def _words(text):
    """Разбить текст на лексемы (без стоп-слов), маленькие, со стеммингом-минимум."""
    stop = {
        "и", "в", "на", "с", "по", "за", "от", "до", "из", "у", "для", "о",
        "не", "ни", "все", "это", "как", "так", "что", "кто", "где", "когда",
        "к", "об", "под", "над", "перед", "между", "чтобы", "потому", "то",
        "двух", "трёх", "трех", "имеет", "быть", "будет", "при", "или",
    }
    out = []
    for w in _re.findall(r"[а-яёa-z0-9]+", text.lower()):
        if w in stop or len(w) < 3:
            continue
        # мини-стем: обрезаем частые окончания для сравнения
        for suf in ("ения", "ений", "ение", "ость", "ного", "тое", "ость"):
            if w.endswith(suf) and len(w) > len(suf) + 2:
                w = w[:-len(suf)]
                break
        out.append(w)
    return out


