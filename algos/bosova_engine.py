# ======================================================================
#  3. ТРОЙСТВЕННОЕ РАССУЖДЕНИЕ «НЕЙРОН-НИГДЕ»
# ======================================================================

def тройственность(query):
    """Тройственное рассуждение: найти в вопросе три опорных слова (A,B,C)
    и построить отношения A↔B, B↔C, A↔C + как C меняет пару A↔B.

    Возвращает словарь с категорией ответа и построенным рассуждением,
    или None, если тройки не нашлось.
    """
    words = _words(query)
    # Кандидаты на роль A/B/C — существительные-концепты (не служебные)
    common = ["страх", "опасность", "контроль", "знание", "незнание", "любовь",
              "ненависть", "доверие", "время", "пространство", "информация",
              "энтропия", "тело", "сила", "движение", "орбита", "нейрон",
              "вес", "вход", "выход", "связь", "отношение", "мера", "степень"]
    present = [w for w in words if w in common]
    # Также берём любые длинные слова как потенциальные элементы, если их 3+ и не стоп
    if len(present) < 3:
        present = [w for w in words if len(w) >= 4]
    if len(present) < 3:
        return None

    A, B, C = present[:3]

    # Мера «силы связи» — как у Шеннона: чем больше общих/длинных лексем,
    # тем выше «неопределённость», которую элемент несёт. Здесь — эвристика.
    def сила(x, y):
        # эвристическая «условная информация»: 0..1
        return min(1.0, len(x) * len(y) / 200.0 + 0.1)

    ab = сила(A, B)
    bc = сила(B, C)
    ac = сила(A, C)
    # как C меняет пару A↔B: C «оттягивает» A и B в свою сторону
    влия_с = (bc + ac) / 2.0
    влияние_на_пару = min(1.0, влия_с * 0.8)

    рассуждение = (
        f"Тройственное рассуждение (нейрон-нигде): {A} – {B} – {C}\n"
        f"Абсолютной «координаты» нет — положение задано отношениями:\n"
        f"  {A}↔{B}: {ab:.2f}\n"
        f"  {B}↔{C}: {bc:.2f}\n"
        f"  {A}↔{C}: {ac:.2f}\n"
        f"Третий элемент {C} меняет пару: усиливает связь пары до ({влияние_на_пару:.2f}) — "
        f"это аналогия с задачей трёх тел и условной информацией Шеннона: "
        f"состояние каждой стороны задаётся не координатой, а отношением к двум другим."
    )
    таблица = ("Таблица решений ×3",
               [f"| СВЯЗЬ | {A}↔{B} | {B}↔{C} | {A}↔{C} |",
                f"| МЕРА  | {ab:.2f} | {bc:.2f} | {ac:.2f} |",
                f"| ВЛИЯНИЕ {C} на пару A↔B | {влияние_на_пару:.2f} |"])
    return {
        "elements": (A, B, C),
        "relations": {"AB": round(ab, 2), "BC": round(bc, 2), "AC": round(ac, 2)},
        "влияние_третьего": round(влияние_на_пару, 2),
        "рассуждение": рассуждение,
        "таблица": таблица,
    }


# ======================================================================
#  ТОЧКА ВХОДА: какую босов-логику применить к вопросу
# ======================================================================

def применить(query):
    """Пытается применить к вопросу выполнимые босовские алгоритмы.

    Возвращает dict вида {kind, answer, scheme} или None, если ничего
    не подходит (тогда Mirro отвечает обычным путём).
    """
    q = query.lower().strip()

    # 1. Выполнимая арифметика по правилам Босовой
    ans, scheme = решить_арифметику(query)
    if ans is not None:
        return {"kind": "bosova_arifmetika", "answer": f"{ans}", "scheme": scheme}

    # 2. Тройственное рассуждение (по мотивам трёх тел + Шеннона)
    if "между" in q or "треть" in q or "отношени" in q or "связ" in q or "влия" in q:
        tr = тройственность(query)
        if tr:
            return {"kind": "troystvennost", "answer": tr["рассуждение"], "scheme": tr["таблица"]}

    # 3. Просьба показать схему мышления
    if "схема" in q or "блок-схем" in q or "алгоритм мышления" in q or "как ты думаешь" in q:
        name = None
        for n in список_схем():
            if n.replace("_", " ") in q or n in q:
                name = n
                break
        s = схема_мышления(name or "вспомогательный")
        return {"kind": "bosova_shema", "answer": "\n".join(s["steps"]),
                "scheme": (s["name"], s["steps"])}

    return None


