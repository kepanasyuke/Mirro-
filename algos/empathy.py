def _detect_rad(message):
    """Определяет тональность и усталость реплики по словарям.
    Короткие основы («рад», «плох», «класс») засчитываем только как отдельные
    слова (словоформы), а не как часть «творад», «хлоплох» и т.п.
    Пустое/None-сообщение → нулевые счётчики. Один return: dict {'pos','neg','fatigue'}."""
    if not isinstance(message, str) or not message.strip():
        return {"pos": 0, "neg": 0, "fatigue": 0}
    m = message.lower()
    pos = sum(1 for w in _POS_SET if w in m)
    neg = sum(1 for w in _NEG_SET if w in m)
    fatigue = sum(1 for w in _FATIGUE_SET if w in m)
    for short in _SHORT_STRICT:
        at_word = _RE_AT_WORD_PATTERNS.get(short)
        if short in _POS_SET and short in m and (at_word is None or not at_word.search(m)):
            pos -= 1
        elif short in _NEG_SET and short in m and (at_word is None or not at_word.search(m)):
            neg -= 1
    return {"pos": max(0, pos), "neg": max(0, neg), "fatigue": max(0, fatigue)}


def observe(message):
    """Обновляет скользящее настроение по новой реплике.
    Разнозначные сигналы в одной реплике не раскачивают настроение (баланс).
    Пустое/None-сообщение → текущее состояние без изменений. Один return: dict."""
    global _emotion, _fatigue
    if not isinstance(message, str) or not message.strip():
        return {"emotion": _emotion, "fatigue": _fatigue}
    d = _detect_rad(message)
    net = (d["pos"] - d["neg"]) if d["pos"] == 0 or d["neg"] == 0 else (d["pos"] - d["neg"]) * 0.5
    if not net == net or (net < -1e6 or net > 1e6):
        net = 0.0
    delta = 0.15 * max(-2, min(2, net))
    if d["pos"] == 0 and d["neg"] == 0:
        # нейтральная реплика мягко тянет к нулю
        delta = -0.02 * _emotion
    _emotion = max(-1.0, min(1.0, _emotion + delta))
    if _emotion != _emotion:
        _emotion = 0.0
    if any(w in m for w in _REST_KW):
        _fatigue = max(0.0, _fatigue - 0.35)
    elif d["fatigue"]:
        _fatigue = min(1.0, _fatigue + 0.25)
    else:
        _fatigue = max(0.0, _fatigue - 0.08)
    if _fatigue != _fatigue:
        _fatigue = 0.0
    return {"emotion": _emotion, "fatigue": _fatigue}


