def empathy_lead(message):
    """Подбирает эмпатичную заставку к ответу под тон собеседника.
    Приоритет: усталость > сильный негатив > лёгкий негатив > позитив.
    Пустое/не-строка/нейтральное → None (заставка не нужна). Один return: str/None."""
    if not isinstance(message, str) or not message.strip():
        return None
    d = _detect_rad(message)
    lead = None
    if d["fatigue"]:
        lead = _pick(_LEAD_RAD["fatigue"])
    elif d["neg"] > 0:
        lead = _pick(_LEAD_RAD["negative_full"] if d["neg"] > 1 else _LEAD_RAD["negative_mild"])
    elif d["pos"] > 0 and d["pos"] > d["neg"]:
        lead = _pick(_LEAD_RAD["positive"])
    return lead or None


def _pick(options):
    """Случайный элемент списка. Пустой список / нет строк → «». Один return: str."""
    import random
    strs = [o for o in (options or []) if isinstance(o, str) and o.strip()]
    if not strs:
        return ""
    return random.choice(strs)


def apply_empathy(message, answer):
    """Оборачивает ответ эмпатичной заставкой под тон сообщения.
    Если ответ уже начинается с похожей заставки — не дублируем.
    Пустой ответ → None исходное значение. Один return: str."""
    out = answer
    if not (answer or ""):
        return out
    if not isinstance(answer, str):
        answer = str(answer or "")
    lead = empathy_lead(message)
    if lead and answer:
        ans = answer
        if not isinstance(lead, str):
            lead = str(lead)
        # уже начали схожей заставкой — пропускаем (анти-дубль)
        lead_key = lead[:12].lower()
        if ans[:24].lower().startswith(lead_key) or \
                any(seg.strip().lower().startswith(lead_key) for seg in ans.split("\n\n")[:3]):
            return ans
        # не дублируем, если пользователь просто спросил настроение/самочувствие
        low = (message or "").lower() if isinstance(message, str) else ""
        if not any(w in low for w in ("как ты себя", "как настроение", "как дела")):
            first = ans[0].lower() if ans else ""
            out = lead + first + ans[1:] if ans else lead
    return out


