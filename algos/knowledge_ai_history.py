def _lookup(query):
    """Находит запись по подстроке. Один return: dict-ответ или None."""
    q = query.lower()
    for key, (answer, authors, idea) in AI_HISTORY.items():
        if key in q:
            footer = "Авторы: " + ", ".join(authors) + ". Идея: " + idea
            return {"content": answer + "\n(" + footer + ")", "kind": "ai_history", "key": key}
    return None


def _any_trigger(query):
    """Есть ли в запросе сигнал «история/кто придумал/архитектура ИИ».
    Один return: bool."""
    q = query.lower()
    return any(t in q for t in ("история", "кто придумал", "кто создал", "автор",
                                "придумал нейро", "откуда взял", "ро|ма", "алгоритм создал"))


def применить(query):
    """Точка входа: вопрос про историю ИИ? Один return: str-ответ или None.

    Срабатывает, если в вопросе найден термин-ключ из справочника (Тьюринг,
    Шеннон, Питтс, ИИТ, ГНВ и т.п.) ИЛИ есть вопрос «кто/как/что такое» с
    таким термином. Прямой lookup не цепляет случайные бытовые вопросы.
    """
    hit = _lookup(query)
    if hit is not None:
        return hit["content"]
    # вопрос «кто/откуда/история» без точного ключа (например «кто автор» без имени)
    if _any_trigger(query):
        return None
    return None


def run_self_check():
    """Быстрая проверка для build --check. Один return: (ok, lines)."""
    cases = [
        ("кто придумал нейрон? что такое питтс", "Питтс"),
        ("кто создал тест тьюринга", "Тьюринг"),
        ("что такое иит", "IIT"),
        ("кто автор теории шеннона", "Шеннон"),
        ("откуда взялась нейросеть", "нейросеть"),
    ]
    ok = True
    lines = []
    for q, sub in cases:
        r = применить(q)
        good = bool(r) and sub.lower() in r.lower()
        ok = ok and good
        lines.append(f"  [{'OK' if good else 'FAIL'}] {q[:40]}")
    return ok, lines