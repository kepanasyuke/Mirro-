def get_scheme(name):
    """Вернуть схему мышления по имени."""
    scheme = BLOCK_SCHEMES.get(name, BLOCK_SCHEMES["sledovanie"])
    return {
        "name": scheme["name"],
        "description": scheme["desc"],
        "steps": scheme["schema"],
    }


def list_schemes():
    """Список всех схем мышления."""
    return {k: v["name"] for k, v in BLOCK_SCHEMES.items()}


def think_about_thinking(query):
    """Как Mirro обдумывает вопрос — показать схему мышления."""
    q = query.lower()
    if "не знаю чего хочу" in q or "хочу" in q and "не знаю" in q:
        return ("Таблица решений для 'не знаю, чего хочу'", [
            "ЕСЛИ хочу → ДЕЛАЮ",
            "ЕСЛИ не хочу → НЕ ДЕЛАЮ",
            "ЕСЛИ не знаю чего хочу → НАЧИНАЮ ДЕЛАТЬ ЧТО-ТО (любой алгоритм лучше, чем ничего)",
        ])
    if "ничего не делать" in q or "лень" in q:
        return ("Алгоритм ничегонеделания (Босова-style)", [
            "НАЧАЛО",
            "ПОКА <лень> ПОВТОРЯТЬ: ничего не делать",
            "ЕСЛИ лень прошла → ТО начать делать",
            "КОНЕЦ",
        ])
    if "шутка" in q or "смешно" in q or "юмор" in q:
        return ("Юмор — это тоже алгоритм", [
            "ВВОД: запрос на шутку",
            "ЕСЛИ тема известна → ПОДОБРАТЬ шутку по теме",
            "ИНАЧЕ → ВЫДАТЬ случайную шутку",
            "ПРОВЕРИТЬ: вызвало ли улыбку? (этот шаг опционален)",
        ])
    return (BLOCK_SCHEMES["sledovanie"]["name"], BLOCK_SCHEMES["sledovanie"]["schema"])


def citata_bosovy():
    """Вернуть случайную цитату Босовой."""
    return random.choice(BOSOVA_CITATY)


