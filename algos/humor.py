_last_shutka = None  # последняя случайная шутка (анти-повтор подряд)


def shutka(tema=None):
    """Вернуть шутку по теме или случайную.
    По теме выбирает ту, у которой больше совпадающих слов с запросом.
    Пустой SHUTKI → «». Случайную — не повторяющую предыдущую подряд.
    Один return: str."""
    global _last_shutka
    if not SHUTKI:
        return ""
    answer = None
    if isinstance(tema, str) and tema.strip():
        tema_lower = tema.lower()
        tema_words = set(tema_lower.split())
        best_score = 0
        for q, a in SHUTKI:
            if not q:
                continue
            q_words = set(q.split())
            score = len(tema_words & q_words)
            if score > best_score:
                best_score = score
                answer = f"— {q.capitalize()}?\n— {a}"
    if best_score == 0:
        answer = None
    if answer is None:
        cands = [a for q, a in SHUTKI if isinstance(a, str) and a and a != _last_shutka] \
            or [a for q, a in SHUTKI if isinstance(a, str) and a]
        answer = random.choice(cands) if cands else ""
        _last_shutka = answer
    return answer


_last_sarkazm = None  # последний ироничный ответ (анти-повтор подряд)


def sarkazm():
    """Вернуть ироничный ответ, не повторяющий предыдущий подряд.
    Пустой SARCASM → «». Один return: str."""
    global _last_sarkazm
    if not SARCASM:
        return ""
    strs = [s for s in SARCASM if isinstance(s, str) and s]
    if not strs:
        return ""
    cands = [s for s in strs if s != _last_sarkazm] or strs
    pick = random.choice(cands)
    _last_sarkazm = pick
    return pick


